/* The Scale card, driven through the real app: read the shape, then every
   field it offers, with real clicks and real Undo.
   node tools/nso_scale_card_drive_check.js               exit 0 = every gate held
   node tools/nso_scale_card_drive_check.js --shots DIR   also write DIR/*.png
                                                          (a scratch directory -
                                                          no screenshot is committed)

   The headless proofs live in tools/nso_section_test.js (the reading),
   tools/nso_box_scale_test.js (Length / Width / Height and the offset on
   boxes and trays) and tools/nso_extend_test.js (Shorten). What this file
   proves is that the card the user sees says what those say, in print terms,
   about pieces made the way a user makes them - and that its verbs do what
   their labels claim:

     1  Stock tube        -> Ring; Length, Outer Ø and Wall rows; no Bore,
                             no Offset, no Longest (it is the Length)
     2  Length shorter / longer, Undo; Whole x 2 and Whole x back to 1
     3  tape_on-edge-single (185 mm on an A1 Mini's 180) -> 5.0 mm too wide;
        Fit to plate brings it inside 180 and says the factor
     4  the 100 x 40 x 25 tray, 2 mm walls and floor, generated by
        tools/nso_box_fixtures.js and loaded through the file input:
        Width, Height, Length - walls and floor bit for bit - and Height under
        the floor, refused with the most Shorten can take
     5  fields repopulate on selection change and on a pose change; Whole x
        resets to 1
     6  the card fits a 900 px-tall window without scrolling, one line a row
     7  Stock box -> Bar, Length / Width / Height
     8  Stock sphere -> the gate in plain words, Offset shown, no L / W / H;
        Longest 50 by a real click (the card hides Longest where a named field
        shows the same number, so a sphere is where it is clicked); Offset +1
        grows it 2 mm, Undo; a shrink through the floor refused

   Every number is printed; the PR quotes them. */

