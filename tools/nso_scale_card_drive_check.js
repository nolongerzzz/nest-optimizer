  check('...and the names stay the piece\'s own, not the plate\'s: still 100 L × 40 W × 25 H', /^100\.0 L × 40\.0 W × 25\.0 H/.test(r3.readout), r3.readout);
  await undo(page);

  console.log('\n=== 6. The card fits a 900 px-tall window ===');
