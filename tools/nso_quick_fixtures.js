#!/usr/bin/env node
/* fixtures/quick/ - small, fast-printing pieces to stress the suite against.
 *
 *     node tools/nso_quick_fixtures.js            regenerate fixtures/quick/
 *     node tools/nso_quick_fixtures.js --check    byte-diff, exit 1 on drift
 *
 * ---------------------------------------------------------------------------
 * WHAT THIS SET IS FOR, AND WHAT IT IS NOT
 * ---------------------------------------------------------------------------
 * The fixtures this repo already has are VALIDATION fixtures: the Thingi10K-
 * style meshes under fixtures/repair/ and fixtures/open/ that are defective on
 * purpose, the traced-line lattices that are one extrusion wide, the skin
 * patches, the raster inputs. Every one of them exists to be a hard case, and
 * most are thousands of triangles of somebody else's geometry.
 *
 * This set is the opposite, deliberately. Every piece here is:
 *
 *   SMALL           the largest is 20 mm on its longest side
 *   CHEAP           12 triangles for the boxes, about 2k for the round ones -
 *                   a tool that runs over the whole set does so in no time
 *   REAL            generated by the shipped code (NSO_Stock), closed, and put
 *                   through the same canonical checker everything else is
 *   QUICK TO PRINT  and that is MEASURED, not claimed - see below
 *
 * So it is a set you can run a tool over without waiting, and a set you can
 * actually PRINT to look at what a tool did. That second half is the bit the
 * existing fixtures cannot do: a 40k-triangle defective scan is not something
 * anybody is going to put on a bed to see whether Seat aligned it properly.
 *
 * ---------------------------------------------------------------------------
 * THE PRINT-TIME FIGURE IS A MODEL, AND THE MODEL IS WRITTEN DOWN
 * ---------------------------------------------------------------------------
 * "Fast-printing" is only worth anything as a number, so each piece carries
 * one, from a stated model rather than a slicer:
 *
 *     extruded length = volume / (layer height * line width)
 *     seconds         = length / speed + layers * layer-change overhead
 *
 * at 0.2 mm layers, a 0.42 mm line, 50 mm/s and 1.5 s a layer. That is a
 * 100%-INFILL SOLID - the worst case, and the one a real slicer will always
 * come in under, because nobody prints a test coupon solid. It is a proxy and
 * it says so; what it is good for is RANKING and BUDGETING, which is all this
 * set needs from it. PRINT_BUDGET_S below is the gate.
 *
 * The volume in that formula is the mesh's own signed volume by the
 * tetrahedron sum, measured off the soup that is about to be written, not a
 * figure carried over from the sizing.
 *
 * ---------------------------------------------------------------------------
 * WHAT IS IN IT
 * ---------------------------------------------------------------------------
 * 1. FIVE PLAIN BOXES, twelve triangles each - three cubes in a size ladder
 *    plus a plate and a bar. Cubes because a cube is the workhorse of half the
 *    drive checks in this repo (Soften's square split, Seat's box-on-box,
 *    Cut's lid, every paint test), and the one that exists - box-20mm.stl - is
 *    the only size there is. The plate and the bar are there because a lot of
 *    code branches on aspect ratio and a cube exercises none of it.
 *
 * 2. THE EIGHT STOCK PRIMITIVES, all sized FROM ONE TARGET. That is not
 *    decoration: nso_stock.js's central claim is that a target's material
 *    figure does not depend on the shape it is made into, so eight pieces
 *    sized from the same target hold the same material and therefore print in
 *    the same time. The set is a ladder in SHAPE with the time held still,
 *    which is exactly what you want when the thing under test is a tool and
 *    not a size.
 *
 * Everything rests on z = 0 and is centred on x and y, which is what
 * NSO_Stock produces and what a bed is. NOTE that fixtures/box-20mm.stl is
 * ORIGIN-CENTRED instead - it predates this and stays as it is, because
 * tools/sculpt_selftest.js and the Soften gate measure against that placement.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { writeSTL } = require('./nso_stl_io.js');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'fixtures', 'quick');

/* nso_stock.js is a classic script, and it resolves NSO_Thickness as a global
   at call time - the same load the page does, and the same one
   tools/nso_stock_test.js does. A require()d copy would look for it in node's
   global scope, where nothing has put it. */
const ctx = {
  Math, Map, Set, console, Array, Object, Number, String, JSON, isFinite, Error,
  Float32Array, Float64Array, Int32Array, Uint32Array, Uint8Array, ArrayBuffer,
  NSO_Thickness: require(path.join(ROOT, 'nso_thickness.js')),
  NSO_Printer: require(path.join(ROOT, 'nso_printer.js'))
};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'nso_stock.js'), 'utf8'), ctx,
  { filename: 'nso_stock.js' });
const S = ctx.NSO_Stock;

/* ------------------------------------------------------------ the figures */

/* THE ONE TARGET the eight primitives are sized from. Small on purpose: a
   10 mm vessel with a 1 mm wall needs 470 mm^3 of stock at the default 30%
   margin, which is two and a half minutes of solid extrusion. The wall is
   comfortably over the 0.42 mm nozzle floor, so the floor stays a guard here
   rather than becoming the figure. */
const TARGET = { height: 10, radius: 5, wall: 1.0 };

/* THE ONE SECOND MEASUREMENT THAT IS NOT LEFT TO ITS DEFAULT, and why.
   Every other shape here takes whatever nso_stock.js resolves for it from
   TARGET, which is the point of the set. An ellipsoid would resolve to the
   target's own h/d of exactly 1 - and an ellipsoid at ratio 1 IS a sphere,
   bit for bit, which nso_stock.js's own self-test asserts. That identity is
   worth having as an assertion and worthless as a FIXTURE: it would put two
   byte-identical files in a set whose value is that each piece is a different
   shape. So the ellipsoid is asked for as a real spheroid. */
const EXTRA = { ellipsoid: { ratio: 1.6 } };

/* 32 rather than the shipped 96. The app wants a smooth blank; a fixture set
   wants to be cheap to walk, and 32 segments is still visibly round - a
   sphere is 1984 triangles instead of 18240, so a tool run over the whole set
   touches about 12k triangles in total. */
const SEGMENTS = 32;

/* The print-time model - see the header. Stated here, echoed into the
   manifest, and gated against PRINT_BUDGET_S so "fast-printing" is a promise
   this file keeps rather than one it makes. */
const PRINT = { layer_mm: 0.2, line_mm: 0.42, speed_mm_s: 50, layer_change_s: 1.5 };
const PRINT_BUDGET_S = 600;              // ten minutes, solid, per piece

/* The plain boxes. Twelve triangles each, and the reason each one is here.

   The cube ladder is 6 / 9 / 12 mm - roughly three times the material at each
   step, so a tool whose cost scales with volume shows it across three points
   rather than two. It stops at 12 because a 12 mm cube is already 8.4 minutes
   of SOLID extrusion and the budget is ten; fixtures/box-20mm.stl is there for
   anything that wants bigger, and is not fast to print. */
const BOXES = [
  ['cube-6mm',      [6, 6, 6],     'the small end of the ladder - a minute and a half solid'],
  ['cube-9mm',      [9, 9, 9],     'the middle of the ladder, about 3x the material of the 6'],
  ['cube-12mm',     [12, 12, 12],  'the large end, about 2.4x again and still inside the budget'],
  ['plate-20x20x2', [20, 20, 2],   'a flat plate: wide, ten layers tall, for anything that branches on a dominant flat face'],
  ['bar-20x5x5',    [20, 5, 5],    'a square-section bar: one long axis, for anything that branches on a dominant LONG axis']
];

/* ---------------------------------------------------------------- measure */

/* The signed volume of a closed soup by the tetrahedron sum, and its bounding
   box. Both measured off the soup that is about to be written rather than
   taken from the sizing, so the manifest describes the FILE. */
function meshVolume(t) {
  let v = 0;
  for (let i = 0; i < t.length; i += 9) {
    const ax = t[i], ay = t[i + 1], az = t[i + 2];
    const bx = t[i + 3], by = t[i + 4], bz = t[i + 5];
    const cx = t[i + 6], cy = t[i + 7], cz = t[i + 8];
    v += (ax * (by * cz - bz * cy) - ay * (bx * cz - bz * cx) + az * (bx * cy - by * cx)) / 6;
  }
  return v;
}

function bbox(t) {
  const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < t.length; i += 3) {
    for (let k = 0; k < 3; k++) {
      if (t[i + k] < lo[k]) lo[k] = t[i + k];
      if (t[i + k] > hi[k]) hi[k] = t[i + k];
    }
  }
  return { lo, hi, size: [hi[0] - lo[0], hi[1] - lo[1], hi[2] - lo[2]] };
}

/* V - E + F on the welded mesh, plus the open and non-manifold edge counts.
   Welded on the EXACT float bits, which is legitimate here and nowhere else:
   every vertex in these pieces is produced by the same expression on both
   sides of the seam it shares, so two coincident vertices are bit-identical
   rather than merely close. tools/mesh_validate.py is still the canonical
   word on these files - this is here so the manifest carries the numbers
   without shelling out to python. */
function topology(t) {
  const vid = new Map(), edge = new Map();
  const key = i => t[i] + ',' + t[i + 1] + ',' + t[i + 2];
  let faces = 0;
  for (let i = 0; i < t.length; i += 9) {
    faces++;
    const v = [];
    for (let k = 0; k < 3; k++) {
      const s = key(i + k * 3);
      if (!vid.has(s)) vid.set(s, vid.size);
      v.push(vid.get(s));
    }
    for (let k = 0; k < 3; k++) {
      const a = v[k], b = v[(k + 1) % 3];
      const ek = a < b ? a + '|' + b : b + '|' + a;
      const rec = edge.get(ek) || { uses: 0, net: 0 };
      rec.uses++; rec.net += (a < b ? 1 : -1);
      edge.set(ek, rec);
    }
  }
  let open = 0, nonmanifold = 0, winding = 0;
  for (const rec of edge.values()) {
    if (rec.uses === 1) open++;
    else if (rec.uses > 2) nonmanifold++;
    else if (rec.net !== 0) winding++;
  }
  const euler = vid.size - edge.size + faces;
  return { verts: vid.size, edges: edge.size, faces,
           open_edges: open, nonmanifold_edges: nonmanifold,
           inconsistent_winding_edges: winding,
           euler, genus: (2 - euler) / 2 };
}

/* The model from the header, applied. `layers` is the piece's own height in
   0.2 mm layers - a flat plate is ten of them and a cube is seventy, which is
   why the layer-change overhead is a separate term and not folded into the
   speed. */
function printTime(volume, heightMm) {
  const layers = Math.ceil(heightMm / PRINT.layer_mm);
  const length = volume / (PRINT.layer_mm * PRINT.line_mm);
  const seconds = length / PRINT.speed_mm_s + layers * PRINT.layer_change_s;
  return { layers, extruded_mm: +length.toFixed(1), seconds: +seconds.toFixed(1) };
}

function describe(name, note, tris) {
  const b = bbox(tris), vol = meshVolume(tris), top = topology(tris);
  const t = printTime(vol, b.size[2]);
  return {
    stl: name + '.stl',
    note,
    tris: tris.length / 9,
    bbox_mm: b.size.map(x => +x.toFixed(4)),
    base_z_mm: +b.lo[2].toFixed(6),
    volume_mm3: +vol.toFixed(4),
    topology: top,
    print: t
  };
}

/* ------------------------------------------------------------------ build */

function buildAll() {
  const out = [];
  for (const [name, [x, y, z], note] of BOXES) {
    out.push({ name, note, tris: S.boxSoup(x, y, z), kind: 'box' });
  }
  for (const shape of S.SHAPES) {
    const made = S.make(Object.assign({ shape, segments: SEGMENTS, profileN: SEGMENTS },
                                      TARGET, EXTRA[shape] || {}));
    if (!made.ok) throw new Error(shape + ': ' + made.reason);
    out.push({
      name: 'shape-' + shape, kind: 'shape', shape, tris: made.soup,
      note: made.sizing.measure_text,
      sizing: {
        need_volume_mm3: +made.sizing.need_volume.toFixed(6),
        analytic_volume_mm3: +made.sizing.volume.toFixed(6),
        built_volume_mm3: +made.sizing.built_volume.toFixed(6),
        polygon_factor: +made.sizing.polygon_factor.toFixed(12)
      }
    });
  }
  return out;
}

function manifest(pieces) {
  const entries = pieces.map(p => {
    const e = describe(p.name, p.note, p.tris);
    e.kind = p.kind;
    if (p.shape) { e.shape = p.shape; e.sizing = p.sizing; }
    return e;
  });
  const slow = entries.reduce((a, b) => (b.print.seconds > a.print.seconds ? b : a));
  return {
    generated_by: 'tools/nso_quick_fixtures.js',
    what: 'small, cheap, fast-printing pieces to stress tools against - see the ' +
          'file header, and fixtures/README.md',
    print_model: Object.assign({
      formula: 'seconds = volume / (layer_mm * line_mm) / speed_mm_s + layers * layer_change_s',
      assumes: 'a 100% infill solid - the worst case, which a real slicer always beats',
      budget_s: PRINT_BUDGET_S
    }, PRINT),
    target: Object.assign({ segments: SEGMENTS }, TARGET),
    per_shape_overrides: EXTRA,
    slowest: { stl: slow.stl, seconds: slow.print.seconds },
    total_tris: entries.reduce((n, e) => n + e.tris, 0),
    total_print_s: +entries.reduce((n, e) => n + e.print.seconds, 0).toFixed(1),
    entries
  };
}

/* ------------------------------------------------------------------- main */

function main() {
  const check = process.argv.includes('--check');
  fs.mkdirSync(OUT, { recursive: true });
  const pieces = buildAll();
  const index = manifest(pieces);

  /* The budget is the generator's own gate, not only the test's: a piece that
     takes an hour to print must not be WRITTEN into a set whose whole claim is
     that it does not. */
  for (const e of index.entries) {
    if (e.print.seconds > PRINT_BUDGET_S) {
      console.log('  REFUSED ' + e.stl + ' - ' + e.print.seconds + ' s solid, over the ' +
        PRINT_BUDGET_S + ' s budget');
      process.exit(1);
    }
    if (e.topology.open_edges || e.topology.nonmanifold_edges ||
        e.topology.inconsistent_winding_edges) {
      console.log('  REFUSED ' + e.stl + ' - not a closed solid: ' +
        JSON.stringify(e.topology));
      process.exit(1);
    }
  }

  let drift = 0;
  for (const p of pieces) {
    const file = path.join(OUT, p.name + '.stl');
    const tmp = file + '.tmp';
    writeSTL(tmp, p.tris, 'NSO quick fixture ' + p.name);
    const buf = fs.readFileSync(tmp); fs.unlinkSync(tmp);
    if (check) {
      const have = fs.existsSync(file) ? fs.readFileSync(file) : null;
      const same = have && have.equals(buf);
      console.log('  ' + (same ? 'ok   ' : 'DRIFT') + ' ' + path.relative(ROOT, file) +
        ' (' + buf.length + ' bytes)' + (same ? '' : have ? ' - was ' + have.length : ' - missing'));
      if (!same) drift++;
    } else {
      fs.writeFileSync(file, buf);
      console.log('  wrote ' + path.relative(ROOT, file) + ' (' + buf.length + ' bytes)');
    }
  }

  const jf = path.join(OUT, 'quick.json');
  const jtxt = JSON.stringify(index, null, 2) + '\n';
  if (check) {
    const have = fs.existsSync(jf) ? fs.readFileSync(jf, 'utf8') : null;
    const same = have === jtxt;
    console.log('  ' + (same ? 'ok   ' : 'DRIFT') + ' ' + path.relative(ROOT, jf));
    if (!same) drift++;
  } else {
    fs.writeFileSync(jf, jtxt);
    console.log('  wrote ' + path.relative(ROOT, jf));
  }

  console.log('');
  for (const e of index.entries) {
    console.log('  ' + e.stl.padEnd(22) + String(e.tris).padStart(6) + ' tris  ' +
      e.bbox_mm.map(x => x.toFixed(2)).join(' x ').padEnd(24) +
      e.volume_mm3.toFixed(1).padStart(9) + ' mm^3  ' +
      (e.print.seconds / 60).toFixed(2).padStart(6) + ' min solid  genus ' + e.topology.genus);
  }
  console.log('\n  ' + index.entries.length + ' pieces, ' + index.total_tris + ' triangles, ' +
    (index.total_print_s / 60).toFixed(1) + ' minutes to print the whole set solid; ' +
    'slowest is ' + index.slowest.stl + ' at ' + (index.slowest.seconds / 60).toFixed(2) + ' min');

  if (check && drift) {
    console.log('\n' + drift + ' fixture(s) drifted - rerun without --check if the change is intended');
    process.exit(1);
  }
  console.log('\n' + (check ? 'fixtures match' : 'fixtures written'));
}

module.exports = { buildAll, manifest, describe, topology, meshVolume, bbox, printTime,
                   OUT, TARGET, SEGMENTS, EXTRA, PRINT, PRINT_BUDGET_S, BOXES };
if (require.main === module) main();
