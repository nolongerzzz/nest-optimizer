#!/usr/bin/env node
/**
 * nest-optimizer / tools / handoff-index.mjs   (npm run handoff:index)
 *
 * Regenerates the list of docs/handoff/*.md inside docs/HANDOFF.md, between the
 * two marker comments. One line per file, sorted by file name, titled by the
 * file's first heading. Nothing else in HANDOFF.md is touched.
 *
 * WHY. HANDOFF.md used to be one 6 500-line file every ticket appended to, so
 * every batch conflicted in it. A ticket now adds docs/handoff/<ticket>.md and
 * re-runs this; after a rebase, re-run it again - never merge the list by hand.
 *
 *   npm run handoff:index            # rewrite the list
 *   node tools/handoff-index.mjs --check   # change nothing; exit 1 if it is stale
 *   ... --root <dir>                  # a tree other than the repo
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const START = '<!-- handoff-index:start - generated by `npm run handoff:index`; do not edit between the markers -->';
export const END = '<!-- handoff-index:end -->';

export function titleOf(text, file) {
  const m = /^#{1,2}\s+(.+?)\s*$/m.exec(text);
  return m ? m[1] : file.replace(/\.md$/, '');
}

export function indexBlock(dir) {
  const files = readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
  const lines = files.map((f) => `- [${titleOf(readFileSync(join(dir, f), 'utf8'), f).replace(/([[\]])/g, '\\$1')}](handoff/${f})`);
  return [START, ...lines, END].join('\n');
}

export function withIndex(text, block) {
  const a = /<!-- handoff-index:start[^>]*-->/.exec(text);
  const b = /<!-- handoff-index:end -->/.exec(text);
  if (!a || !b || b.index < a.index) return null;
  return text.slice(0, a.index) + block + text.slice(b.index + b[0].length);
}

function main() {
  const ri = process.argv.indexOf('--root'); // a tree other than the repo (the manifest's samples)
  const root = ri >= 0 ? resolve(process.argv[ri + 1]) : ROOT;
  const file = join(root, 'docs', 'HANDOFF.md');
  const text = readFileSync(file, 'utf8');
  const next = withIndex(text, indexBlock(join(root, 'docs', 'handoff')));
  if (next === null) {
    console.error('handoff-index: docs/HANDOFF.md has no index markers - run tools/migrate-handoff.mjs first');
    process.exit(2);
  }
  const n = next.split('\n').filter((l) => /^- \[.*\]\(handoff\//.test(l)).length;
  if (process.argv.includes('--check')) {
    if (next !== text) { console.error(`handoff-index: docs/HANDOFF.md's list is stale - run \`npm run handoff:index\``); process.exit(1); }
    console.log(`handoff-index: ${n} entries, list is current`);
    return;
  }
  if (next !== text) writeFileSync(file, next);
  console.log(`handoff-index: ${n} entries${next === text ? ', unchanged' : ', rewritten'}`);
}

if (process.argv[1] && join(process.argv[1]) === fileURLToPath(import.meta.url)) main();
