#!/usr/bin/env node
/*
 * Build a sliced-project fixture: fixtures/3mf/toolpath-ground-truth.gcode.3mf
 *
 * WHY THIS EXISTS AND WHAT IT IS NOT
 * The importer's whole claim is that it recovers a move's real printed width
 * from that move's own E value - not from a setting, not from a default. The
 * only way to prove that is to write a file whose correct answer is known
 * exactly, then read it back and compare. So this generator goes the other way
 * round the flow model: it is handed the width and height each line should
 * print at, computes the E the slicer would have written with
 * `areaFromWidth()`, and emits that. The check then asserts the importer
 * recovers the widths and angles it started from, to 1e-9.
 *
 * This is a correctness fixture, not a sample of Bambu's output. It is
 * deliberately structured like a real Bambu slice - M83 relative E, G92 E0,
 * `; CHANGE_LAYER` / `; Z_HEIGHT:` / `; LAYER_HEIGHT:` / `; FEATURE:` tags,
 * travel moves, retractions, Z hops, the trailing config comment block - so the
 * parser is exercised on the same shapes, but the geometry is a test pattern
 * and no claim is made that Bambu would slice anything this way.
 *
 * Run: node tools/gcode-test/make-fixture.js
 */
'use strict';

const fs = require('fs');
const path = require('path');
const G = require('../../nso-gcode-lines.js');
const NSO3MF = require('../../nso-3mf.js');

const FIL_D = 1.75;
const LAYER_H = 0.2;
const REPO = path.join(__dirname, '..', '..');
const OUT = path.join(REPO, 'fixtures', '3mf', 'toolpath-ground-truth.gcode.3mf');

// ---------------------------------------------------------------------------
// The ground truth. Every line here is an exact intent: this polyline, at this
// width, in this feature, on this layer. The check reads these same numbers.
// ---------------------------------------------------------------------------
const PATTERN = [
  // feature,               width,  polyline (x,y pairs) - no two consecutive
  // segments collinear, so no two line solids share a face.
  ['Outer wall',       0.42, [[10, 10], [30, 10], [30, 30], [10, 30], [10, 10]]],
  ['Inner wall',       0.45, [[10.6, 10.6], [29.4, 10.6], [29.4, 29.4], [10.6, 29.4], [10.6, 10.6]]],
  ['Sparse infill',    0.45, [[11.5, 11.5], [28.5, 28.5]]],
  ['Sparse infill',    0.45, [[28.5, 11.5], [11.5, 28.5]]],
  ['Support',          0.38, [[34, 10], [44, 10], [44, 20], [34, 20], [34, 10]]],
  ['Support interface',0.40, [[34.5, 21], [43.5, 21]]],
  ['Support interface',0.40, [[43.5, 22], [34.5, 22]]],
  ['Support interface',0.40, [[34.5, 23], [43.5, 23]]]
];
const LAYERS = 3;

function eFor(width, height, dist) {
  // Inverse of the reader: area -> volume -> filament length.
  const area = G.areaFromWidth(width, height);
  return (area * dist) / (Math.PI * FIL_D * FIL_D / 4);
}

function fmt(n) { return Number(n.toFixed(5)).toString(); }

/** @returns {{text: string, expected: object[]}} */
function buildGcode() {
  const L = [];
  const expected = [];

  L.push('; generated by NSO tools/gcode-test/make-fixture.js - synthetic ground truth');
  L.push('; HEADER_BLOCK_START');
  L.push('; total layer number: ' + LAYERS);
  L.push('; HEADER_BLOCK_END');
  L.push('M73 P0 R2');
  L.push('G90');
  L.push('M83');
  L.push('G21');
  L.push('G28');
  L.push('G92 E0');
  L.push('; EXECUTABLE_BLOCK_START');

  for (let layer = 0; layer < LAYERS; layer++) {
    const z = +( (layer + 1) * LAYER_H ).toFixed(5);
    L.push('; CHANGE_LAYER');
    L.push('; Z_HEIGHT: ' + fmt(z));
    L.push('; LAYER_HEIGHT: ' + fmt(LAYER_H));
    L.push('; layer num/total_layer_count: ' + (layer + 1) + '/' + LAYERS);
    L.push('G1 Z' + fmt(z + 0.4) + ' F12000');   // Z hop - carries no E
    L.push('G1 Z' + fmt(z) + ' F12000');

    for (const [feature, width, pts] of PATTERN) {
      L.push('; FEATURE: ' + feature);
      L.push('G1 X' + fmt(pts[0][0]) + ' Y' + fmt(pts[0][1]) + ' F12000');  // travel
      L.push('G1 E0.8 F1800');                                              // prime, no XY
      for (let i = 1; i < pts.length; i++) {
        const [x0, y0] = pts[i - 1];
        const [x1, y1] = pts[i];
        const dist = Math.hypot(x1 - x0, y1 - y0);
        const e = eFor(width, LAYER_H, dist);
        L.push('G1 X' + fmt(x1) + ' Y' + fmt(y1) + ' E' + fmt(e) + ' F1200');
        expected.push({
          layer, feature, width, height: LAYER_H, z,
          x0, y0, x1, y1,
          length: dist,
          angle: Math.atan2(y1 - y0, x1 - x0)
        });
      }
      L.push('G1 E-0.8 F1800');                                             // retract, no XY
    }
  }

  L.push('; EXECUTABLE_BLOCK_END');
  L.push('M107');
  L.push('M104 S0');
  // Bambu's trailing config block - this is where filament_diameter comes from.
  L.push('; filament_diameter = ' + FIL_D);
  L.push('; layer_height = ' + LAYER_H);
  L.push('; nozzle_diameter = 0.4');
  return { text: L.join('\n') + '\n', expected };
}

const MODEL_XML =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">\n' +
  ' <resources/>\n <build/>\n</model>\n';

const RELS_XML =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' +
  '<Relationship Id="rel-1" Target="/3D/3dmodel.model" ' +
  'Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>\n';

const CONTENT_TYPES =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' +
  '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' +
  '<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>' +
  '<Default Extension="gcode" ContentType="text/x.gcode"/></Types>\n';

function enc(s) { return new TextEncoder().encode(s); }

async function main() {
  const { text, expected } = buildGcode();
  const bytes = await NSO3MF.buildZip([
    { name: '[Content_Types].xml', data: enc(CONTENT_TYPES) },
    { name: '_rels/.rels', data: enc(RELS_XML) },
    { name: '3D/3dmodel.model', data: enc(MODEL_XML) },
    { name: 'Metadata/plate_1.gcode', data: enc(text) }
  ]);
  fs.writeFileSync(OUT, Buffer.from(bytes));
  fs.writeFileSync(OUT.replace(/\.3mf$/, '.expected.json'),
    JSON.stringify({ filamentDiameter: FIL_D, layerHeight: LAYER_H, layers: LAYERS, moves: expected }, null, 1) + '\n');
  console.log('wrote ' + path.relative(REPO, OUT) + ' (' + bytes.length + ' bytes, ' +
              expected.length + ' expected moves)');
}

if (require.main === module) main().catch(e => { console.error(e); process.exit(1); });
module.exports = { buildGcode, eFor, PATTERN, LAYERS, LAYER_H, FIL_D };
